    /// <param name="text"> The text to display on the TextField. </param>
    /// <param name="skin"> The Skin holding the <see cref="TextFieldStyle"/>. </param>
    public TextField( string? text, Skin skin )
        : this( text, skin.Get< TextFieldStyle >() )
    {
    }

    /// <summary>
    /// Creates a new TextField object with the supplied text and <see cref="Skin"/>
    /// containing the names <see cref="TextFieldStyle"/>.
    /// </summary>
    /// <param name="text"> The text to display on the TextField. </param>
    /// <param name="skin"> The Skin holding the <see cref="TextFieldStyle"/>. </param>
    /// <param name="styleName"> The name of the TextFieldStyle to use. </param>
    public TextField( string? text, Skin skin, string styleName )
        : this( text, skin.Get< TextFieldStyle >( styleName ) )
    {
    }

    /// <summary>
    /// Creates a new TextField object with the supplied text and <see cref="TextFieldStyle"/>.
    /// </summary>
    /// <param name="text"> The text to display on the TextField. </param>
    /// <param name="style"> The <see cref="TextFieldStyle"/> to use. </param>
    public TextField( string? text, TextFieldStyle style )
    {
        _clipboard     = Engine.App.Clipboard;
        _blink         = new BlinkTaskManager( this );
        _keyRepeat     = new KeyRepeatTaskManager( this );
        _inputListener = new TextFieldClickListener( this );

        _blink.Create();
        _keyRepeat.Create();

        SetStyleSafe( style );
        SetText( text );
        SetSize( GetPrefWidthUnchecked(), GetPrefHeightUnchecked() );
    }

    /// <summary>
    /// If true, the text in this text field will be shown as bullet characters.
    /// <see cref="PasswordCharacter"/>
    /// </summary>
    public bool PasswordMode
    {
        get => _passwordMode;
        set
        {
            _passwordMode = value;
            UpdateDisplayText();
        }
    }

    /// <summary>
    /// The character to use for hiding the password, typically a bullet character but can
    /// be any character.
    /// </summary>
    public char PasswordCharacter
    {
        get => _passwordCharacter;
        set
        {
            _passwordCharacter = value;

            if ( PasswordMode )
            {
                UpdateDisplayText();
            }
        }
    }

    /// <inheritdoc />
    public override float GetPrefWidth()
    {
        return GetPrefWidthUnchecked();
    }

    /// <summary>
    /// The preferred width of the textfield based on the items it contains. This
    /// method is a wrapper for <see cref="GetPrefWidth()"/>, and is provided to
    /// allow calling safely from constructors.
    /// </summary>
    /// <returns> The preferred width of the textfield. </returns>
    protected float GetPrefWidthUnchecked()
    {
        return 150;
    }

    /// <inheritdoc />
    public override float GetPrefHeight()
    {
        return GetPrefHeightUnchecked();
    }

    /// <summary>
    /// The preferred height of the textfield based on the items it contains. This
    /// method is a wrapper for <see cref="GetPrefHeight()"/>, and is provided to
    /// allow calling safely from constructors.
    /// </summary>
    /// <returns> The preferred height of the textfield. </returns>
    protected float GetPrefHeightUnchecked()
    {
        float topAndBottom = 0;
        float minHeight    = 0;

        if ( _style.Background != null )
        {
            topAndBottom = Math.Max
                (
                 topAndBottom,
                 _style.Background.BottomHeight + _style.Background.TopHeight
                );
            minHeight = Math.Max( minHeight, _style.Background.MinHeight );
        }

        if ( _style.FocusedBackground != null )
        {
            topAndBottom = Math.Max
                (
                 topAndBottom,
                 _style.FocusedBackground.BottomHeight + _style.FocusedBackground.TopHeight
                );
            minHeight = Math.Max( minHeight, _style.FocusedBackground.MinHeight );
        }

        if ( _style.DisabledBackground != null )
        {
            topAndBottom = Math.Max
                (
                 topAndBottom,
                 _style.DisabledBackground.BottomHeight + _style.DisabledBackground.TopHeight
                );
            minHeight = Math.Max( minHeight, _style.DisabledBackground.MinHeight );
        }

        return Math.Max( topAndBottom + TextHeight, minHeight );
    }

    /// <summary>
    /// Get the current style of the actor
    /// </summary>
    public virtual TextFieldStyle GetStyle() => _style;

    /// <summary>
    /// Set the current style of the actor
    /// </summary>
    public virtual void SetStyle( TextFieldStyle style )
    {
        SetStyleSafe( style );
    }

    /// <summary>
    /// Sets the current style of the actor.
    /// This method is a wrapper for <see cref="SetStyleSafe(TextFieldStyle)"/>, and is
    /// provided to allow calling safely from constructors.
    /// </summary>
    /// <param name="style"> The new style to set. </param>
    protected void SetStyleSafe( TextFieldStyle style )
    {
        Guard.Against.Null( style.Font );

        _style = style;

        TextHeight = style.Font.GetCapHeight() - ( style.Font.GetDescent() * 2 );

        if ( !string.IsNullOrEmpty( Text ) )
        {
            UpdateDisplayText();
        }

        InvalidateHierarchy();
    }

    /// <summary>
    /// Calculates the render offsets and visible character range for the text in the TextField.
    /// This method ensures that the text cursor and selected text remain visible within the
    /// current viewable area of the TextField, and adjusts the rendering as needed based on the
    /// glyph positions, background, and alignment.
    /// </summary>
    public virtual void CalculateOffsets()
    {
        float           visibleWidth = GetWidth();
        ISceneDrawable? background   = GetBackgroundDrawable();

        if ( background != null )
        {
            visibleWidth -= background.LeftWidth + background.RightWidth;
        }

        int     glyphCount     = GlyphPositions.Count;
        float[] glyphPositions = GlyphPositions.ToArray();

        // Check if the cursor has gone out the left or right side of
        // the visible area and adjust renderOffset if necessary.
        float distance = glyphPositions[ Math.Max( 0, Cursor - 1 ) ] + _renderOffset;

        if ( distance <= 0 )
        {
            _renderOffset -= distance;
        }
        else
        {
            int   index = Math.Min( glyphCount - 1, Cursor + 1 );
            float minX  = glyphPositions[ index ] - visibleWidth;

            if ( -_renderOffset < minX )
            {
                _renderOffset = -minX;
            }
        }

        // Prevent renderOffset from starting too close to the end, eg after text was deleted.
        var   maxOffset = 0f;
        float width     = glyphPositions[ glyphCount - 1 ];

        for ( int i = glyphCount - 2; i >= 0; i-- )
        {
            float x = glyphPositions[ i ];

            if ( ( width - x ) > visibleWidth )
            {
                break;
            }

            maxOffset = x;
        }

        if ( -_renderOffset > maxOffset )
        {
            _renderOffset = -maxOffset;
        }

        // calculate first visible char based on render offset
        _visibleTextStart = 0;

        var startX = 0f;

        for ( var i = 0; i < glyphCount; i++ )
        {
            if ( glyphPositions[ i ] >= -_renderOffset )
            {
                _visibleTextStart = i;
                startX            = glyphPositions[ i ];

                break;
            }
        }

        // calculate last visible char based on visible width and render offset
        int   end  = _visibleTextStart + 1;
        float endX = visibleWidth - _renderOffset;

        for ( int n = Math.Min( DisplayText.Length, glyphCount ); end <= n; end++ )
        {
            if ( glyphPositions[ end ] > endX )
            {
                break;
            }
        }

        _visibleTextEnd = Math.Max( 0, end - 1 );

        if ( ( _textAlign & Align.Left ) == 0 )
        {
            TextOffset = visibleWidth - glyphPositions[ _visibleTextEnd ] - FontOffset + startX;

            if ( ( _textAlign & Align.Center ) != 0 )
            {
                TextOffset = ( float )Math.Round( TextOffset * 0.5f );
            }
        }
        else
        {
            TextOffset = startX + _renderOffset;
        }

        // calculate selection x position and width
        if ( HasSelection )
        {
            Guard.Against.Null( _style );

            int   minIndex = Math.Min( Cursor, SelectionStart );
            int   maxIndex = Math.Max( Cursor, SelectionStart );
            float minX     = Math.Max( glyphPositions[ minIndex ] - glyphPositions[ _visibleTextStart ], -TextOffset );
            float maxX = Math.Min
                (
                 glyphPositions[ maxIndex ] - glyphPositions[ _visibleTextStart ],
                 visibleWidth - TextOffset
                );

            _selectionX     = minX;
            _selectionWidth = maxX - minX - _style.Font.FontData.CursorX;
        }
    }

    /// <summary>
    /// Determines the index of the letter located under the specified x-coordinate
    /// relative to the current cursor line's glyph positions.
    /// </summary>
    /// <param name="x">The x-coordinate to check for a corresponding letter.</param>
    /// <returns>The index of the letter under the specified x-coordinate.</returns>
    protected virtual int LetterUnderCursor( float x )
    {
        x -= TextOffset + FontOffset - _style.Font.FontData.CursorX - GlyphPositions[ _visibleTextStart ];

        ISceneDrawable? background = GetBackgroundDrawable();

        if ( background != null )
        {
            x -= background.LeftWidth;
        }

        int     n              = GlyphPositions.Count;
        float[] glyphPositions = GlyphPositions.ToArray();

        for ( var i = 1; i < n; i++ )
        {
            if ( glyphPositions[ i ] > x )
            {
                if ( ( glyphPositions[ i ] - x ) <= ( x - glyphPositions[ i - 1 ] ) )
                {
                    return i;
                }

                return i - 1;
            }
        }

        return n - 1;
    }

    /// <summary>
    /// Returns <c>true</c> if the specified character is considered a word character.
    /// </summary>
    /// <param name="c">The character to check.</param>
    /// <returns><c>true</c> if the character is a word character; otherwise, <c>false</c>.</returns>
    protected virtual bool IsWordCharacter( char c )
    {
        return char.IsLetterOrDigit( c );
    }

    /// <summary>
    /// Returns the indices of the word under the cursor at the specified position.
    /// </summary>
    /// <param name="at">The position of the cursor.</param>
    /// <returns>An array containing the indices of the word under the cursor.</returns>
    protected virtual int[] WordUnderCursor( int at )
    {
        string text  = Text;
        int    right = Text.Length;
        var    left  = 0;
        int    index = at;

        if ( at >= text.Length )
        {
            left  = text.Length;
            right = 0;
        }
        else
        {
            for ( ; index < right; index++ )
            {
                if ( !IsWordCharacter( text[ index ] ) )
                {
                    right = index;

                    break;
                }
            }

            for ( index = at - 1; index > -1; index-- )
            {
                if ( !IsWordCharacter( text[ index ] ) )
                {
                    left = index + 1;

                    break;
                }
            }
        }

        return [ left, right ];
    }

    /// <summary>
    /// Retrieves the start and end indices of the word under the cursor based on
    /// the specified x-coordinate.
    /// </summary>
    /// <param name="x">
    /// The x-coordinate relative to the text field, used to determine the word under the cursor.
    /// </param>
    /// <returns>
    /// An array of two integers, where the first element represents the start index and
    /// the second element represents the end index of the word under the cursor.
    /// </returns>
    protected virtual int[] WordUnderCursor( float x )
    {
        return WordUnderCursor( LetterUnderCursor( x ) );
    }

    /// <summary>
    /// Determines whether the specified size is within the maximum allowable length.
    /// </summary>
    /// <param name="size">The size to evaluate against the maximum length.</param>
    /// <returns>
    /// <c>true</c> if the size is less than the maximum length or if no maximum length is set;
    /// otherwise, <c>false</c>.
    /// </returns>
    protected virtual bool WithinMaxLength( int size )
    {
        return ( MaxLength <= 0 ) || ( size < MaxLength );
    }

    /// <summary>
    /// Retrieves the appropriate background drawable for the TextField based on its current state.
    /// </summary>
    /// <returns>The <see cref="ISceneDrawable"/> representing the background.
    /// This could be the disabled background if the TextField is disabled,
    /// the focused background if the TextField has focus, or the default background otherwise.</returns>
    protected virtual ISceneDrawable? GetBackgroundDrawable()
    {
        if ( Disabled && ( _style.DisabledBackground != null ) )
        {
            return _style.DisabledBackground;
        }

        if ( ( _style.FocusedBackground != null ) && HasKeyboardFocus() )
        {
            return _style.FocusedBackground;
        }

        return _style.Background;
    }

    /// <inheritdoc />
    public override void Draw( IBatch batch, float parentAlpha )
    {
        bool focused = HasKeyboardFocus();

        if ( ( focused != _focused ) || ( focused && ( _blinkTask?.Status != TaskStatus.Running ) ) )
        {
            _focused = focused;
            _blink.Cancel();
            _cursorOn = focused;

            if ( focused )
            {
                _blink.Start();
            }
            else
            {
                _keyRepeat.Cancel();
            }
        }
        else if ( !focused )
        {
            _cursorOn = false;
        }

        BitmapFont font = _style.Font;

        ISceneDrawable? background = GetBackgroundDrawable();

        float x            = GetX();
        float y            = GetY();
        float width        = GetWidth();
        float height       = GetHeight();
        var   bgLeftWidth  = 0f;
        var   bgRightWidth = 0f;

        batch.SetColor( ActorColor.R, ActorColor.G, ActorColor.B, ActorColor.A * parentAlpha );

        if ( background != null )
        {
            background.Draw( batch, x, y, width, height );
            bgLeftWidth  = background.LeftWidth;
            bgRightWidth = background.RightWidth;
        }

        float textY = GetTextY( font, background );

        CalculateOffsets();

        if ( focused && HasSelection )
        {
            ISceneDrawable? selection = _style.Selection;

            if ( selection != null )
            {
                DrawSelection( selection, batch, font, x + bgLeftWidth, y + textY );
            }
        }

        float yOffset = font.Flipped ? -TextHeight : 0;

        if ( DisplayText.Length == 0 )
        {
            if ( !focused )
            {
                BitmapFont messageFont = _style.MessageFont ?? font;

                if ( _style.MessageFontColor != null )
                {
                    messageFont.SetColor
                        (
                         _style.MessageFontColor.R,
                         _style.MessageFontColor.G,
                         _style.MessageFontColor.B,
                         _style.MessageFontColor.A * ActorColor.A * parentAlpha
                        );
                }
                else
                {
                    messageFont.SetColor( Color.Gray, ActorColor.A * parentAlpha );
                }

                DrawMessageText
                    (
                     batch,
                     messageFont,
                     x + bgLeftWidth,
                     y + textY + yOffset,
                     width - bgLeftWidth - bgRightWidth
                    );
            }
        }
        else
        {
            Color? fontColor = Disabled
                                   ? _style.DisabledFontColor
                                   : focused
                                       ? _style.FocusedFontColor
                                       : _style.FontColor;

            Guard.Against.Null( fontColor ); // Or force fontColor to Color.White?

            font.SetColor( fontColor.R, fontColor.G, fontColor.B, fontColor.A * ActorColor.A * parentAlpha );
            DrawText( batch, font, x + bgLeftWidth, y + textY + yOffset );
        }

        if ( !Disabled && _cursorOn )
        {
            ISceneDrawable? cursorPatch = _style.Cursor;

            if ( cursorPatch != null )
            {
                DrawCursor( cursorPatch, batch, font, x + bgLeftWidth, y + textY );
            }
        }
    }

    /// <summary>
    /// Calculates the Y-coordinate for text rendering within the TextField,
    /// considering the font metrics and optional background drawable.
    /// </summary>
    /// <param name="font">The font used for rendering the text.</param>
    /// <param name="background">The optional background drawable that affects the placement of the text.</param>
    /// <return>The calculated Y-coordinate for rendering the text.</return>
    protected virtual float GetTextY( BitmapFont font, ISceneDrawable? background )
    {
        float height = GetHeight();
        float textY  = ( TextHeight / 2 ) + font.GetDescent();

        if ( background != null )
        {
            float bottom = background.BottomHeight;

            textY = textY + ( ( height - background.TopHeight - bottom ) / 2 ) + bottom;
        }
        else
        {
            textY += height / 2;
        }

        if ( font.GetUseIntegerPositions() )
        {
            textY = ( int )textY;
        }

        return textY;
    }

    /// <summary>
    /// Draws the selection background of the text field in the specified area.
    /// </summary>
    /// <param name="selection">The drawable object representing the selection background.</param>
    /// <param name="batch">The rendering batch used for drawing the selection.</param>
    /// <param name="font">The font used to retrieve text metrics such as descent.</param>
    /// <param name="x">
    /// The X-coordinate where the selection should be drawn, adjusted by text and font offsets.
    /// </param>
    /// <param name="y">
    /// The Y-coordinate where the selection should be drawn, adjusted by text height and font descent.
    /// </param>
    protected virtual void DrawSelection( ISceneDrawable selection, IBatch batch, BitmapFont font, float x, float y )
    {
        selection.Draw
            (
             batch,
             x + TextOffset + _selectionX + FontOffset,
             y - TextHeight - font.GetDescent(),
             _selectionWidth,
             TextHeight
            );
    }

    /// <summary>
    /// Renders the text of the TextField using the specified font and drawing batch at the given coordinates.
    /// </summary>
    /// <param name="batch">The drawing batch used for rendering the text.</param>
    /// <param name="font">The font used to render the text.</param>
    /// <param name="x">The x-coordinate for the text's position.</param>
    /// <param name="y">The y-coordinate for the text's position.</param>
    protected virtual void DrawText( IBatch batch, BitmapFont font, float x, float y )
    {
        font.Draw
            (
             batch,
             DisplayText,
             x + TextOffset,
             y,
             _visibleTextStart,
             _visibleTextEnd,
             0,
             Align.Left,
             false
            );
    }

    /// <summary>
    /// Renders the message text using the specified font and batch at the given position
    /// and within the specified maximum width.
    /// </summary>
    /// <param name="batch">The batch used to render the text.</param>
    /// <param name="font">The font used to draw the message text.</param>
    /// <param name="x">The x-coordinate at which to start drawing the text.</param>
    /// <param name="y">The y-coordinate at which to start drawing the text.</param>
    /// <param name="maxWidth">The maximum width within which the text should be drawn.</param>
    protected virtual void DrawMessageText( IBatch batch, BitmapFont font, float x, float y, float maxWidth )
    {
        font.Draw( batch, MessageText, x, y, 0, MessageText.Length, maxWidth, _textAlign, false, "..." );
    }

    /// <summary>
    /// Renders the text cursor at the specified position using the given parameters.
    /// </summary>
    /// <param name="cursorPatch">The drawable cursor representation to be rendered.</param>
    /// <param name="batch">The batch used to render the cursor.</param>
    /// <param name="font">The font associated with the text rendering in the field.</param>
    /// <param name="x">The x-coordinate where the cursor should be drawn.</param>
    /// <param name="y">The y-coordinate where the cursor should be drawn.</param>
    protected virtual void DrawCursor( ISceneDrawable cursorPatch, IBatch batch, BitmapFont font, float x, float y )
    {
        cursorPatch.Draw
            (
             batch,
             x + TextOffset + GlyphPositions[ Cursor ]
           - GlyphPositions[ _visibleTextStart ]
           + FontOffset
           + font.FontData.CursorX,
             y - TextHeight - font.GetDescent(),
             cursorPatch.MinWidth,
             TextHeight
            );
    }

    /// <summary>
    /// Updates the display text of the TextField to reflect its current content.
    /// Handles password mode, glyph validation, and layout recalculations.
    /// This method ensures that the visible text, glyph positions, and cursor/selection indexes
    /// are consistent with the TextField's internal state.
    /// </summary>
    public virtual void UpdateDisplayText()
    {
        BitmapFont     font       = _style.Font;
        BitmapFontData data       = font.FontData;
        string         text       = Text;
        int            textLength = text.Length;
        var            buffer     = new StringBuilder();

        for ( var i = 0; i < textLength; i++ )
        {
            char c = text[ i ];
            buffer.Append( data.HasGlyph( c ) ? c : ' ' );
        }

        var newDisplayText = buffer.ToString();

        if ( _passwordMode && data.HasGlyph( _passwordCharacter ) )
        {
            _passwordBuffer ??= new StringBuilder( newDisplayText.Length );

            if ( _passwordBuffer.Length > textLength )
            {
                _passwordBuffer.Length = textLength;
            }
            else
            {
                for ( int i = _passwordBuffer.Length; i < textLength; i++ )
                {
                    _passwordBuffer.Append( _passwordCharacter );
                }
            }

            DisplayText = _passwordBuffer.ToString();
        }
        else
        {
            DisplayText = newDisplayText;
        }

        GlyphLayout.SetText( font, DisplayText.Replace( '\r', ' ' ).Replace( '\n', ' ' ) );
        GlyphPositions.Clear();

        float x = 0;

        if ( GlyphLayout.Runs.Count > 0 )
        {
            GlyphLayout.GlyphRun run       = GlyphLayout.Runs.First();
            List< float >        xAdvances = run.XAdvances;

            FontOffset = xAdvances.First();

            for ( int i = 1, n = xAdvances.Count; i < n; i++ )
            {
                GlyphPositions.Add( x );
                x += xAdvances[ i ];
            }
        }
        else
        {
            FontOffset = 0;
        }

        GlyphPositions.Add( x );

        _visibleTextStart = Math.Min( _visibleTextStart, GlyphPositions.Count - 1 );
        _visibleTextEnd   = MathUtils.Clamp( _visibleTextEnd, _visibleTextStart, GlyphPositions.Count - 1 );

        if ( SelectionStart > newDisplayText.Length )
        {
            SelectionStart = textLength;
        }
    }

    /// <summary>
    /// Sets the text for this textfield.
    /// </summary>
    /// <param name="str"> The new text to be set for the TextField. </param>
    public void SetText( string? str )
    {
        str ??= string.Empty;

        if ( str.Equals( Text ) ) return;

        ClearSelection();

        string oldText = Text;
        Text = string.Empty;

        Paste( str, false );

        if ( ProgrammaticChangeEvents )
        {
            ChangeText( oldText, Text );
        }

        Cursor = 0;
    }

    /// <summary>
    /// Copies the contents of this TextField to the <see cref="IClipboard"/>
    /// implementation set on this TextField.
    /// </summary>
    public void Copy()
    {
        if ( HasSelection && !PasswordMode )
        {
            _clipboard?.Contents = Text.Substring
                (
                 Math.Min( Cursor, SelectionStart ),
                 Math.Max( Cursor, SelectionStart )
                );
        }
    }

    /// <summary>
    /// Copies the selected contents of this TextField to the <see cref="IClipboard"/>
    /// implementation set on this TextField, then removes it.
    /// </summary>
    public void Cut()
    {
        Cut( ProgrammaticChangeEvents );
    }

    /// <summary>
    /// Removes the currently selected text from the field and copies it to the clipboard.
    /// If no text is selected, the method does nothing.
    /// </summary>
    /// <param name="fireChangeEvent">
    /// Indicates whether to trigger change events after the text modification.
    /// </param>
    public void Cut( bool fireChangeEvent )
    {
        if ( HasSelection && !PasswordMode )
        {
            Copy();

            Cursor = Delete( fireChangeEvent );

            UpdateDisplayText();
        }
    }

    /// <summary>
    /// Inserts the specified content into the text field at the current cursor position or
    /// replaces the currently selected text, optionally firing a change event to notify of
    /// the content modification.
    /// </summary>
    /// <param name="content">
    /// The text to paste into the text field. If null, no action is performed.
    /// </param>
    /// <param name="fireChangeEvent">
    /// Determines whether a change event should be triggered as a result of this operation.
    /// </param>
    public void Paste( string? content, bool fireChangeEvent )
    {
        if ( content == null )
        {
            return;
        }

        var buffer     = new StringBuilder();
        int textLength = Text.Length;

        if ( HasSelection )
        {
            textLength -= Math.Abs( Cursor - SelectionStart );
        }

        Debug.Assert( _style != null, $"{nameof( _style )} != null" );

        BitmapFontData data = _style.Font.FontData;

        for ( int i = 0, n = content.Length; i < n; i++ )
        {
            if ( !WithinMaxLength( textLength + buffer.Length ) )
            {
                break;
            }

            char c = content[ i ];

            if ( !( WriteEnters && c is Newline or CarriageReturn ) )
            {
                if ( c is '\r' or '\n' )
                {
                    continue;
                }

                if ( _onlyFontChars && !data.HasGlyph( c ) )
                {
                    continue;
                }

                if ( ( Filter != null ) && !Filter.AcceptChar( this, c ) )
                {
                    continue;
                }
            }

            buffer.Append( c );
        }

        content = buffer.ToString();

        if ( HasSelection )
        {
            Cursor = Delete( fireChangeEvent );
        }

        if ( fireChangeEvent )
        {
            ChangeText( Text, Insert( Cursor, content, Text ) );
        }
        else
        {
            Text = Insert( Cursor, content, Text );
        }

        UpdateDisplayText();
        Cursor += content.Length;
    }

    /// <summary>
    /// Inserts the specified text into the given string at the specified position
    /// and returns the resulting string.
    /// </summary>
    /// <param name="position">The position in the destination string where the text should be inserted.</param>
    /// <param name="text">The text to insert into the destination string.</param>
    /// <param name="to">The destination string where the text will be inserted.</param>
    /// <returns>The resulting string after the text has been inserted.</returns>
    public string Insert( int position, string text, string to )
    {
        if ( to.Length == 0 )
        {
            return text;
        }

        return to.Substring( 0, position ) + text + to.Substring( position, to.Length );
    }

    /// <summary>
    /// Deletes the currently selected text in the TextField or the character near the
    /// cursor if no text is selected.
    /// </summary>
    /// <param name="fireChangeEvent">
    /// Indicates whether a change event should be fired after the text is modified.
    /// </param>
    /// <returns>The new cursor position after the deletion.</returns>
    public int Delete( bool fireChangeEvent )
    {
        int from     = SelectionStart;
        int to       = Cursor;
        int minIndex = Math.Min( from, to );
        int maxIndex = Math.Max( from, to );

        string newText = ( minIndex > 0 ? Text.Substring( 0, minIndex ) : string.Empty )
                       + ( maxIndex < Text.Length ? Text.Substring( maxIndex, Text.Length ) : string.Empty );

        if ( fireChangeEvent )
        {
            ChangeText( Text, newText );
        }
        else
        {
            Text = newText;
        }

        ClearSelection();

        return minIndex;
    }

    /// <summary>
    /// Sets the <see cref="Stage.GetKeyboardFocus()"/> to the next TextField. If no next
    /// text field is found, the onscreen keyboard is hidden. Does nothing if the text field
    /// is not in a stage.
    /// </summary>
    /// <param name="up">
    /// If true, the text field with the same or next smallest y coordinate is found, else
    /// the next highest.
    /// </param>
    public void Next( bool up )
    {
        if ( GetStage() == null || Parent == null )
        {
            return;
        }

        TextField current       = this;
        Vector2   currentCoords = current.Parent.LocalToStageCoordinates( _tmp2.Set( current.GetX(), current.GetY() ) );

        var stage = GetStage();

        if ( stage == null ) return;

        while ( true )
        {
            TextField? textField = current.FindNextTextField( stage.Actors, null, _tmp1, currentCoords, up );

            if ( textField == null )
            {
                // Try to wrap around.
                if ( up )
                {
                    currentCoords.Set( -float.MaxValue, -float.MaxValue );
                }
                else
                {
                    currentCoords.Set( float.MaxValue, float.MaxValue );
                }

                textField = current.FindNextTextField( stage.Actors, null, _tmp1, currentCoords, up );
            }

            if ( textField == null )
            {
                Engine.Input.SetOnscreenKeyboardVisible( false );

                break;
            }

            if ( stage.GetKeyboardFocus() == textField )
            {
                textField.SelectAll();

                break;
            }

            current = textField;
            currentCoords.Set( _tmp1 );
        }
    }

    /// <summary>
    /// Finds the next best suited <see cref="TextField"/> to focus on based on the provided parameters.
    /// </summary>
    /// <param name="actors">The list of actors to search through.</param>
    /// <param name="best">The currently identified best candidate for the next <see cref="TextField"/>.</param>
    /// <param name="bestCoords">The coordinates of the best candidate so far.</param>
    /// <param name="currentCoords">The current coordinates used for comparison.</param>
    /// <param name="up">A flag indicating the search direction. If true, searches upward; otherwise, searches downward.</param>
    /// <returns>The next best <see cref="TextField"/> to focus on, or null if no suitable candidate is found.</returns>
    private TextField? FindNextTextField( SnapshotArrayList< Actor > actors,
                                          TextField? best,
                                          Vector2 bestCoords,
                                          Vector2 currentCoords,
                                          bool up )
    {
        for ( int i = 0, n = actors.Size; i < n; i++ )
        {
            Actor actor = actors.GetAt( i );

            if ( actor is TextField textField )
            {
                if ( textField == this )
                {
                    continue;
                }

                if ( textField.Disabled || !textField.FocusTraversal || !textField.AscendantsVisible() )
                {
                    continue;
                }

                Vector2? actorCoords =
                    textField.Parent?.LocalToStageCoordinates( _tmp3.Set( textField.GetX(), textField.GetY() ) );

                if ( actorCoords is null )
                {
                    continue;
                }

                bool below = !actorCoords.Y.Equals( currentCoords.Y ) && ( ( actorCoords.Y < currentCoords.Y ) ^ up );
                bool right = actorCoords.Y.Equals( currentCoords.Y ) && ( ( actorCoords.X > currentCoords.X ) ^ up );

                if ( !below && !right )
                {
                    continue;
                }

                bool better = ( best == null )
                           || ( !actorCoords.Y.Equals( bestCoords.Y ) && ( ( actorCoords.Y > bestCoords.Y ) ^ up ) );

                if ( !better )
                {
                    better = actorCoords.Y.Equals( bestCoords.Y ) && ( ( actorCoords.X < bestCoords.X ) ^ up );
                }

                if ( better )
                {
                    best = textField;
                    bestCoords.Set( actorCoords );
                }
            }
            else if ( actor is Group group )
            {
                //TODO: Refactor to remove recursiveness 
                best = FindNextTextField( group.Children, best, bestCoords, currentCoords, up );
            }
        }

        return best;
    }

    /// <summary>
    /// Returns True if the text was changed.
    /// </summary>
    /// <param name="oldText"> The old text value before modification. </param>
    /// <param name="newText"> The new text value after modification. </param>
    private bool ChangeText( string? oldText, string? newText )
    {
        if ( ( oldText == null ) || ( newText == null ) )
        {
            return false;
        }

        if ( string.Compare( oldText, newText, StringComparison.CurrentCulture ) == 0 )
        {
            return false;
        }

        Text = newText;

        var changeEvent = PoolsMap.Obtain< ChangeListener.ChangeEvent >();

        bool cancelled = Fire( changeEvent );

        if ( cancelled )
        {
            Text = oldText;
        }

        PoolsMap.Free< ChangeListener.ChangeEvent >( changeEvent );

        return !cancelled;
    }

    /// <summary>
    /// Determines whether the cursor should continue moving based on the given index and offset.
    /// </summary>
    /// <param name="index">The current position of the cursor in the text.</param>
    /// <param name="offset">The offset to apply to the current cursor position.</param>
    /// <returns>True if the cursor should continue moving; otherwise, false.</returns>
    protected virtual bool ContinueCursor( int index, int offset )
    {
        return IsWordCharacter( Text[ index + offset ] );
    }

    /// <summary>
    /// Adjusts the position of the cursor within the text field.
    /// </summary>
    /// <param name="forward">
    /// Specifies the direction of cursor movement. If true, moves the cursor forward;
    /// otherwise, moves it backward.
    /// </param>
    /// <param name="jump">
    /// Indicates whether to skip over groups of characters (e.g., words) when moving the cursor.
    /// </param>
    protected virtual void MoveCursor( bool forward, bool jump )
    {
        int limit      = forward ? Text.Length : 0;
        int charOffset = forward ? 0 : -1;

        while ( ( forward ? ++Cursor < limit : --Cursor > limit ) && jump )
        {
            if ( !ContinueCursor( Cursor, charOffset ) )
            {
                break;
            }
        }
    }

    /// <summary>
    /// Sets the selection range in the text field based on the provided start and end indices.
    /// </summary>
    /// <param name="selectionStart">
    /// The starting index of the selection range. Must be greater than or equal to 0.
    /// </param>
    /// <param name="selectionEnd">
    /// The ending index of the selection range. Must be greater than or equal to 0.
    /// </param>
    /// <exception cref="ArgumentException">
    /// Thrown if either <paramref name="selectionStart"/> or <paramref name="selectionEnd"/>
    /// is less than 0.
    /// </exception>
    public virtual void SetSelection( int selectionStart, int selectionEnd )
    {
        if ( selectionStart < 0 )
        {
            throw new ArgumentException( "SelectionStart must be >= 0" );
        }

        if ( selectionEnd < 0 )
        {
            throw new ArgumentException( "selectionEnd must be >= 0" );
        }

        selectionStart = Math.Min( Text.Length, selectionStart );
        selectionEnd   = Math.Min( Text.Length, selectionEnd );

        if ( selectionEnd == selectionStart )
        {
            ClearSelection();

            return;
        }

        if ( selectionEnd < selectionStart )
        {
            ( selectionEnd, selectionStart ) = ( selectionStart, selectionEnd );
        }

        HasSelection   = true;
        SelectionStart = selectionStart;
        Cursor         = selectionEnd;
    }

    /// <summary>
    /// Selects all text within the TextField, extending the selection from the beginning
    /// of the text to the end. This method is used to highlight all characters
    /// for actions like copying, cutting, or replacing text.
    /// </summary>
    public void SelectAll()
    {
        SetSelection( 0, Text.Length );
    }

    /// <summary>
    /// Clears the current text selection in the TextField, if any.
    /// Sets the <see cref="HasSelection"/> property to false.
    /// </summary>
    public void ClearSelection()
    {
        HasSelection = false;
    }

    /// <summary>
    /// Sets the cursor position and clears any selection.
    /// </summary>
    public void SetCursorPosition( int cursorPosition )
    {
        if ( cursorPosition < 0 )
        {
            throw new ArgumentException( "cursorPosition must be >= 0" );
        }

        ClearSelection();

        Cursor = Math.Min( cursorPosition, Text.Length );
    }

