    /// A listener class responsible for handling input events specifically for <see cref="TextField"/> widgets.
    /// <para>
    /// This class extends <see cref="ClickListener"/> and processes user interactions such as clicks, touches,
    /// and key events. It provides methods to manage the behavior of the text field when input events occur,
    /// including cursor movement, text selection, and keyboard event handling.
    /// </para>
    /// <para>
    /// It includes functionality to navigate to the start or end of a text field, position the cursor based
    /// on touch input, and handle key repeat tasks for continuous key presses. Additionally, it manages
    /// focus traversal based on typed characters.
    /// </para>
    /// <para>
    /// Designed to be used internally by <see cref="TextField"/> and its subclasses, the listener enhances
    /// interactive user experiences and ensures compatibility with the event-driven architecture of the UI framework.
    /// </para>
    [PublicAPI]
    public class TextFieldClickListener : ClickListener
    {
        private readonly TextField _tf;

        protected TextFieldClickListener()
        {
            _tf = new TextField( string.Empty, new Skin() );
        }

        protected internal TextFieldClickListener( TextField tf )
        {
            _tf = tf;
        }

        /// <inheritdoc />
        public override void OnClicked( InputEvent ev, float x, float y )
        {
            int count = TapCount % 4;

            if ( count == 0 )
            {
                _tf.ClearSelection();
            }

            if ( count == 2 )
            {
                int[] array = _tf.WordUnderCursor( x );
                _tf.SetSelection( array[ 0 ], array[ 1 ] );
            }

            if ( count == 3 )
            {
                _tf.SelectAll();
            }
        }

        /// <inheritdoc />
        public override bool OnTouchDown( InputEvent? ev, float x, float y, int pointer, int button )
        {
            if ( !base.OnTouchDown( ev, x, y, pointer, button ) )
            {
                return false;
            }

            if ( ( pointer == 0 ) && ( button != 0 ) )
            {
                return false;
            }

            if ( _tf.Disabled )
            {
                return true;
            }

            SetCursorPosition( x, y );
            _tf.SelectionStart = _tf.Cursor;

            var tfStage = _tf.GetStage();
        
            if ( tfStage != null )
            {
                tfStage.SetKeyboardFocus( _tf );
            }

            _tf._keyboard.Show( true );
            _tf.HasSelection = true;

            return true;
        }

        /// <inheritdoc />
        public override void OnTouchDragged( InputEvent? ev, float x, float y, int pointer )
        {
            base.OnTouchDragged( ev, x, y, pointer );
            SetCursorPosition( x, y );
        }

        /// <inheritdoc />
        public override void OnTouchUp( InputEvent? ev, float x, float y, int pointer, int button )
        {
            if ( _tf.SelectionStart == _tf.Cursor )
            {
                _tf.HasSelection = false;
            }

            base.OnTouchUp( ev, x, y, pointer, button );
        }

        /// <summary>
        /// Moves the cursor to the beginning of the text field.
        /// </summary>
        /// <param name="jump">
        /// Indicates whether the operation should be treated as a jump, typically for
        /// selection purposes.
        /// </param>
        protected virtual void GoHome( bool jump )
        {
            _tf.Cursor = 0;
        }

        /// <summary>
        /// Positions the cursor at the end of the text within the TextField or TextArea.
        /// </summary>
        /// <param name="jump">If true, may include additional logic for navigation behavior.</param>
        protected virtual void GoEnd( bool jump )
        {
            _tf.Cursor = _tf.Text.Length;
        }

        /// <inheritdoc />
        public override bool OnKeyDown( InputEvent? ev, int keycode )
        {
            if ( _tf.Disabled )
            {
                return false;
            }

            _tf._cursorOn = _tf._focused;
            _tf._blink.Cancel();

            if ( _tf._focused )
            {
//                Timer.schedule( _tf._blinkTask, _tf._blinkTime, _tf._blinkTime );
            }

            if ( !_tf.HasKeyboardFocus() )
            {
                return false;
            }

            var  repeat  = false;
            bool ctrl    = InputUtils.CtrlKey();
            bool jump    = ctrl && !_tf._passwordMode;
            var  handled = true;

            if ( ctrl )
            {
                switch ( keycode )
                {
                    case IInput.Keys.V:
                        _tf.Paste( _tf._clipboard?.Contents, true );
                        repeat = true;

                        break;

                    case IInput.Keys.C:
                    case IInput.Keys.Insert:
                        _tf.Copy();

                        return true;

                    case IInput.Keys.X:
                        _tf.Cut( true );

                        return true;

                    case IInput.Keys.A:
                        _tf.SelectAll();

                        return true;

                    case IInput.Keys.Z:
                        string oldText = _tf.Text;

                        _tf.SetText( _tf._undoText );
                        _tf._undoText = oldText;
                        _tf.UpdateDisplayText();

                        return true;

                    default:
                        handled = false;

                        break;
                }
            }

            if ( InputUtils.ShiftKey() )
            {
                switch ( keycode )
                {
                    case IInput.Keys.Insert:
                        _tf.Paste( _tf._clipboard?.Contents, true );

                        break;

                    case IInput.Keys.ForwardDel:
                        _tf.Cut( true );

                        break;
                }

                int temp = _tf.Cursor;

                switch ( keycode )
                {
                    case IInput.Keys.Left:
                        _tf.MoveCursor( false, jump );
                        repeat  = true;
                        handled = true;

                        break;

                    case IInput.Keys.Right:
                        _tf.MoveCursor( true, jump );
                        repeat  = true;
                        handled = true;

                        break;

                    case IInput.Keys.Home:
                        GoHome( jump );
                        handled = true;

                        break;

                    case IInput.Keys.End:
                        GoEnd( jump );
                        handled = true;

                        break;
                }

                if ( !_tf.HasSelection )
                {
                    _tf.SelectionStart = temp;
                    _tf.HasSelection   = true;
                }
            }
            else
            {
                // Cursor movement or other keys (kills selection).
                switch ( keycode )
                {
                    case IInput.Keys.Left:
                        _tf.MoveCursor( false, jump );
                        _tf.ClearSelection();
                        repeat  = true;
                        handled = true;

                        break;

                    case IInput.Keys.Right:
                        _tf.MoveCursor( true, jump );
                        _tf.ClearSelection();
                        repeat  = true;
                        handled = true;

                        break;

                    case IInput.Keys.Home:
                        GoHome( jump );
                        _tf.ClearSelection();
                        handled = true;

                        break;

                    case IInput.Keys.End:
                        GoEnd( jump );
                        _tf.ClearSelection();
                        handled = true;

                        break;
                }
            }

            _tf.Cursor = MathUtils.Clamp( _tf.Cursor, 0, _tf.Text.Length );

            if ( repeat )
            {
                ScheduleKeyRepeatTask( keycode );
            }

            return handled;
        }

        /// <inheritdoc />
        public override bool OnKeyUp( InputEvent? ev, int keycode )
        {
            if ( _tf.Disabled )
            {
                return false;
            }

            _tf._keyRepeat.Cancel();

            return true;
        }

        /// <summary>
        /// Checks if focus traversal should be triggered. The default implementation
        /// uses <see cref="TextField.FocusTraversal"/> and the typed character,
        /// depending on the OS.
        /// </summary>
        /// <param name="character"> The character that triggered a possible focus traversal. </param>
        /// <returns>
        /// true if the focus should change to the <see cref="TextField.Next(bool)"/> input field.
        /// </returns>
        protected virtual bool CheckFocusTraversal( char character )
        {
            return _tf.FocusTraversal
                && ( ( character == Tab )
                  || ( character is CarriageReturn or Newline && ( Platform.IsAndroid || Platform.IsIos ) ) );
        }

        /// <inheritdoc />
        public override bool OnKeyTyped( InputEvent? ev, char character )
        {
            if ( _tf.Disabled )
            {
                return false;
            }

            // Disallow "typing" most ASCII control characters, which would
            // show up as a space when onlyFontChars is true.
            switch ( character )
            {
                case Backspace:
                case Tab:
                case Newline:
                case CarriageReturn:
                    break;

                default:
                    if ( character < 32 )
                    {
                        return false;
                    }

                    break;
            }

            if ( !_tf.HasKeyboardFocus() )
            {
                return false;
            }

            if ( Platform.IsMac && Engine.Input.IsKeyPressed( IInput.Keys.Sym ) )
            {
                return true;
            }

            if ( CheckFocusTraversal( character ) )
            {
                _tf.Next( InputUtils.ShiftKey() );
            }
            else
            {
                bool enter     = character is CarriageReturn or Newline;
                bool delete    = character == DeleteKey;
                bool backspace = character == Backspace;

                bool add = enter
                               ? _tf.WriteEnters
                               : !_tf._onlyFontChars || _tf._style.Font.FontData.HasGlyph( character );

                bool remove = backspace || delete;

                if ( add || remove )
                {
                    string oldText   = _tf.Text;
                    int    oldCursor = _tf.Cursor;

                    if ( remove )
                    {
                        if ( _tf.HasSelection )
                        {
                            _tf.Cursor = _tf.Delete( false );
                        }
                        else
                        {
                            if ( backspace && ( _tf.Cursor > 0 ) )
                            {
                                _tf.Text = _tf.Text.Substring( 0, _tf.Cursor - 1 )
                                         + _tf.Text.Substring( _tf.Cursor-- );

                                _tf._renderOffset = 0;
                            }

                            if ( delete && ( _tf.Cursor < _tf.Text.Length ) )
                            {
                                _tf.Text = _tf.Text.Substring( 0, _tf.Cursor ) + _tf.Text.Substring( _tf.Cursor + 1 );
                            }
                        }
                    }

                    if ( add && !remove )
                    {
                        // Character may be added to the text.
                        if ( !enter && ( _tf.Filter != null ) && !_tf.Filter.AcceptChar( _tf, character ) )
                        {
                            return true;
                        }

                        if ( !_tf.WithinMaxLength
                                 (
                                  _tf.Text.Length
                                - ( _tf.HasSelection
                                        ? Math.Abs( _tf.Cursor - _tf.SelectionStart )
                                        : 0 )
                                 ) )
                        {
                            return true;
                        }

                        if ( _tf.HasSelection )
                        {
                            _tf.Cursor = _tf.Delete( false );
                        }

                        string insertion = enter ? "\n" : character.ToString();

                        _tf.Text = _tf.Insert( _tf.Cursor++, insertion, _tf.Text );
                    }

                    if ( _tf.ChangeText( oldText, _tf.Text ) )
                    {
                        long time = TimeUtils.Millis();

                        if ( ( time - 750 ) > _tf._lastChangeTime )
                        {
                            _tf._undoText = oldText;
                        }

                        _tf._lastChangeTime = time;
                        _tf.UpdateDisplayText();
                    }
                    else
                    {
                        _tf.Cursor = oldCursor;
                    }
                }
            }

            _tf.Listener?.KeyTyped( _tf, character );

            return true;
        }

        /// <summary>
        /// Sets the cursor position within the text field.
        /// </summary>
        /// <param name="x"> X coordinate. </param>
        /// <param name="y"> Y coordinate. </param>
        protected virtual void SetCursorPosition( float x, float y )
        {
            _tf.Cursor    = _tf.LetterUnderCursor( x );
            _tf._cursorOn = _tf._focused;

            _tf._blink.Cancel();

            if ( _tf._focused )
            {
//TODO:
//                Timer.Schedule( _tf._blinkTask, _tf._blinkTime, _tf._blinkTime );
            }
        }

        /// <summary>
        /// 
        /// </summary>
        /// <param name="keycode"></param>
        protected virtual void ScheduleKeyRepeatTask( int keycode )
        {
            if ( _tf._keyRepeat.KeyCode != keycode )
            {
                _tf._keyRepeat.KeyCode = keycode;
            }
        }
    }

